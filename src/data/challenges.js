import { addDays, format, subDays } from "date-fns";

// Deadlines are relative to *today* so the demo never looks expired.
// Legacy `deadline` label is kept (derived from deadlineDays) so existing UI keeps working.
// IDs 1-6 are stable; new sample challenges are 7-12. Everything here is SAMPLE data.

const deadlineLabel = (days) => format(addDays(new Date(), days), "d MMM yyyy");
const deadlineISO = (days) => addDays(new Date(), days).toISOString();
const postedISO = (daysAgo) => subDays(new Date(), daysAgo).toISOString();

function makeChallenge(c) {
  return {
    ...c,
    deadline: deadlineLabel(c.deadlineDays),
    deadlineDate: deadlineISO(c.deadlineDays),
    postedDate: postedISO(c.postedDaysAgo ?? 6),
  };
}

